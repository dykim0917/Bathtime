export function normalizeOnsenTermGuideCopy(value) {
  let text = String(value ?? '');
  for (const [pattern, replacement] of onsenTermGuideReplacements) {
    text = text.replace(pattern, replacement);
  }
  for (const [pattern, replacement] of politeSentenceReplacements) {
    text = text.replace(pattern, replacement);
  }
  return text.replace(/\s+/g, ' ').trim();
}

function normalizeOnsenNoteCopy(value) {
  let text = normalizeOnsenTermGuideCopy(value);
  for (const [pattern, replacement] of politeNoteReplacements) {
    text = text.replace(pattern, replacement);
  }
  return text.replace(/\s+/g, ' ').trim();
}

function hasNumber(value) {
  return typeof value === 'number' && Number.isFinite(value);
}

function createEvidenceNote(row) {
  const counts = row.evidence_counts ?? {};
  const parts = [];
  if (hasNumber(counts.directReviewCount)) parts.push(`직접 읽은 후기 ${counts.directReviewCount.toLocaleString('ko-KR')}건`);
  if (hasNumber(counts.onsenReviewCount)) parts.push(`온천 관련 ${counts.onsenReviewCount.toLocaleString('ko-KR')}건`);
  if (hasNumber(counts.directBodyPlatformCount)) parts.push(`본문 확인 플랫폼 ${counts.directBodyPlatformCount}개`);
  return parts.length > 0 ? parts.join(', ') : row.evidence_note;
}

function unique(values) {
  return [...new Set(values.map((value) => String(value ?? '').trim()).filter(Boolean))];
}

export function applyOnsenCopyQa(row) {
  const copy = onsenCopyQaOverrides[row.slug];
  if (!copy) {
    return {
      ...row,
      summary: normalizeOnsenTermGuideCopy(row.summary),
      primary_bath: normalizeOnsenTermGuideCopy(row.primary_bath),
      operation_notes: unique((row.operation_notes ?? []).map(normalizeOnsenNoteCopy)),
      evidence_note: createEvidenceNote(row),
    };
  }

  return {
    ...row,
    summary: normalizeOnsenTermGuideCopy(copy.summary),
    primary_bath: normalizeOnsenTermGuideCopy(copy.primary_bath),
    operation_notes: unique(copy.operation_notes.map(normalizeOnsenNoteCopy)),
    evidence_note: createEvidenceNote(row),
  };
}

export function findForbiddenOnsenCopyTerms(row) {
  const text = [
    normalizeOnsenTermGuideCopy(row.summary),
    normalizeOnsenTermGuideCopy(row.primary_bath),
    ...(row.operation_notes ?? []).map(normalizeOnsenNoteCopy),
  ].join(' ');
  return forbiddenPublicCopyTerms.filter((term) => text.includes(term));
}
